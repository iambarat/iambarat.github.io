#!/usr/bin/env python3
"""Refresh playlist.js from your Spotify playlist.

Run this after you add, remove or reorder songs on Spotify:
    python3 update-playlist.py
then commit and push playlist.js. Spotify's embed lists at most 100 songs.
"""
import json
import re
import urllib.request

# The part after /playlist/ in your playlist's share link (without ?si=...).
PLAYLIST_ID = "1BfTjBDeMFvSf0MVyojVtk"

url = "https://open.spotify.com/embed/playlist/" + PLAYLIST_ID
req = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"})
html = urllib.request.urlopen(req).read().decode("utf-8")

data = re.search(r'<script id="__NEXT_DATA__"[^>]*>(.*?)</script>', html, re.S)
entity = json.loads(data.group(1))["props"]["pageProps"]["state"]["data"]["entity"]

playlist = {
    "id": PLAYLIST_ID,
    "name": entity["name"],
    "tracks": [
        {
            "id": t["uri"].split(":")[-1],
            "title": t["title"],
            "artist": t["subtitle"],
            "duration": t["duration"],
        }
        for t in entity["trackList"]
        if t.get("isPlayable", True)
    ],
}

with open("playlist.js", "w", encoding="utf-8") as f:
    f.write("// Generated by update-playlist.py. Rerun it after you change the playlist on Spotify.\n")
    f.write("window.PLAYLIST = ")
    json.dump(playlist, f, ensure_ascii=False, indent=1)
    f.write(";\n")

print("Saved %d songs from \"%s\" to playlist.js" % (len(playlist["tracks"]), playlist["name"]))
